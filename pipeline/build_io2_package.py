# -*- coding: utf-8 -*-
"""
Turn the raw LIRR access network into a P2 / IO2-ready instance.

Adds, on top of nodes.csv / links.csv / od_am.csv / paths.csv:

  links_p2.csv        link fare tau_a, surplus phi_a, PURC weight ell_a,
                      capacity, provision and capacity costs
  segments.csv        destination-based segments (the default |Q|=6) and the
                      OD-pair segments (|Q|=3948), with demand
  b_node.csv          node-balance right-hand side b_{i,n} per segment
  f_seg_link.csv      ground-truth f*_{i,a} (destination segments)
  f_seg_link_od.csv   ground-truth f*_{i,a} (OD-pair segments)
  fare_projection.csv the link-additive projection of the LIRR zone fare,
                      with the residual that Assumption 3 costs here
  sampling_plans.csv  every (design, rate, replication) draw as a seed +
                      summary; the draws themselves are regenerated by
                      sampling.py, which is deterministic
  observations/       one materialised O_F per (design, rate) at rep 0
"""
import os, json, hashlib
import numpy as np
import pandas as pd
from scipy.optimize import nnls

D = os.path.dirname(os.path.abspath(__file__))
OUT = D
os.makedirs(f"{D}/observations", exist_ok=True)

VOT = 0.367           # $/min, must match params_true.csv
nodes = pd.read_csv(f"{D}/nodes.csv")
links = pd.read_csv(f"{D}/links.csv")
paths = pd.read_csv(f"{D}/paths.csv")
od = pd.read_csv(f"{D}/od_am.csv")
flow = pd.read_csv(f"{D}/link_flows_true.csv").set_index("link_id").flow_true
links["flow_true"] = links.link_id.map(flow).fillna(0.0)

zone_of = dict(zip(nodes.node_id, nodes.node_type))
name_of = dict(zip(nodes.node_id, nodes.name))

# ===================================================== 1. link-additive fare
# The LIRR fare is a zone-pair table, so it is NOT link additive: Assumption 3
# is violated by construction. P2 needs a link fare tau_a. Take the flow-
# weighted least-squares projection onto link-additive form and report what
# the restriction costs.
rail = links[links.link_type == "RAIL"].link_id.tolist()
ridx = {a: j for j, a in enumerate(rail)}
rp = paths[paths.kind == "RAIL"].copy()

# path LIRR fare = money - access cost - egress fare
acc_cost = {}
for r in links[links.link_type.isin(["ACCESS_DRIVE", "ACCESS_TRANSIT"])].itertuples():
    acc_cost[r.link_id] = r.user_cost_usd
egr_fare = dict(zip(links[links.link_type == "EGRESS"].link_id,
                    links[links.link_type == "EGRESS"].fare_usd))

# The published fare is a zone-pair table. P2 needs a link price tau_a, and
# the seller block allocates capacity by link-level revenue, so the link fares
# must be both link additive and spread over every link that carries riders.
# Rail fares are therefore a two-part tariff:
#     tau_a = c_T * 1[a enters a NYC terminal] + r * miles_a ,
# where the terminal-entering links are the rail links that are only ever the
# last rail link of a path (into Penn, Grand Central Madison and Atlantic
# Terminal), so every City Terminal Zone path pays c_T exactly once. (c_T, r)
# is the flow-weighted least-squares fit to F_p, the published peak one-way
# fare of path p (origin zone -> terminal zone, build_network.lirr_fare), at the
# reference (stage-1) path flows. Paths ending at Jamaica or Woodside (0.04% of
# reference flow) never use a terminal-entering link and pay r * miles only.
# Exact link-additive fits exist but are degenerate (37 of 128 rail links at
# $0), and the seller then deploys almost no capacity on those links; a pure
# per-mile tariff misprices the published fares badly (R2 -0.41).
# This replaces the earlier NNLS + uniform per-mile reallocation, whose target
# wrongly included parking and auto operating cost on drive-access paths.
import build_network as BN
st_zone = dict(zip(nodes.name, nodes.fare_zone))
miles = dict(zip(links.link_id, links.length_mi))
seqs = [[a for a in r.link_ids.split("|") if a in ridx] for r in rp.itertuples()]
_nonlast = {a for q in seqs for a in q[:-1]}
TERMINAL_LINKS = sorted({q[-1] for q in seqs} - _nonlast)
F_p = np.array([BN.lirr_fare(int(st_zone[r.station]), r.terminal) for r in rp.itertuples()])
m_p = np.array([sum(miles[a] for a in q) for q in seqs])
e_p = np.array([float(q[-1] in TERMINAL_LINKS) for q in seqs])
w = np.maximum(rp.flow.to_numpy(float), 0.0)
_sw = np.sqrt(w)
(c_T, rate), *_ = np.linalg.lstsq(np.c_[e_p, m_p] * _sw[:, None], F_p * _sw, rcond=None)
c_T, rate = float(c_T), float(rate)
mi_rail = links.set_index("link_id").length_mi.reindex(rail).to_numpy()
tau_rail = rate * mi_rail + c_T * np.isin(rail, TERMINAL_LINKS)
print(f"two-part rail tariff: ${c_T:.4f} on {len(TERMINAL_LINKS)} terminal-entering links "
      f"{TERMINAL_LINKS} + ${rate:.5f}/mi")
pred = c_T * e_p + rate * m_p
resid = pred - F_p
rmse = float(np.sqrt(np.average(resid**2, weights=w)))
mae = float(np.average(np.abs(resid), weights=w))
r2 = float(1 - np.average(resid**2, weights=w) /
           np.average((F_p - np.average(F_p, weights=w))**2, weights=w))
print(f"link-additive rail fares ({BN.FARE_SCHEDULE}); vs published path "
      f"fares: weighted RMSE ${rmse:.3f}, MAE ${mae:.3f}, R2 {r2:.4f}, "
      f"mean path fare ${np.average(F_p, weights=w):.2f}")

pd.DataFrame(dict(link_id=rail, tau_link_usd=np.round(tau_rail, 6))).to_csv(
    f"{OUT}/fare_projection.csv", index=False)
pd.DataFrame([dict(quantity="schedule", value=BN.FARE_SCHEDULE),
              dict(quantity="terminal_charge_usd", value=round(c_T, 6)),
              dict(quantity="per_mile_rate_usd", value=round(rate, 6)),
              dict(quantity="terminal_links", value=" ".join(TERMINAL_LINKS)),
              dict(quantity="flow_share_paths_err_gt_1c", value=round(float(w[np.abs(pred - F_p) > 0.01].sum() / w.sum()), 6)),
              dict(quantity="weighted_rmse_usd", value=round(rmse, 5)),
              dict(quantity="weighted_mae_usd", value=round(mae, 5)),
              dict(quantity="weighted_r2", value=round(r2, 6)),
              dict(quantity="mean_path_fare_usd",
                   value=round(float(np.average(F_p, weights=w)), 4)),
              dict(quantity="n_rail_paths", value=len(F_p))]).to_csv(
    f"{OUT}/fare_additivity_residual.csv", index=False)
pd.DataFrame(dict(path_id=rp.path_id.to_numpy(), station=rp.station.to_numpy(),
                  terminal=rp.terminal.to_numpy(), fare_published=F_p,
                  rail_miles=np.round(m_p, 4), fare_link_additive=np.round(pred, 4),
                  ref_flow=np.round(w, 5))).to_csv(f"{OUT}/fare_path_check.csv", index=False)

# ============================================== 2. P2 link table (tau, phi, ell)
tau = dict(zip(rail, tau_rail))
links["tau_usd"] = [tau.get(a, 0.0) for a in links.link_id]
links.loc[links.link_type == "ACCESS_TRANSIT", "tau_usd"] = \
    links.loc[links.link_type == "ACCESS_TRANSIT", "fare_usd"]
links.loc[links.link_type == "EGRESS", "tau_usd"] = \
    links.loc[links.link_type == "EGRESS", "fare_usd"]
# the parking charge is the administered price on the capacitated PARK link
links.loc[links.link_type == "PARK", "tau_usd"] = \
    links.loc[links.link_type == "PARK", "fare_usd"]

# phi_a: link surplus net of fare. Fares enter utility with unit coefficient
# (Assumption 2), so phi carries time and non-fare money only.
nonfare = (links.user_cost_usd - links.fare_usd).clip(lower=0)
links["phi_usd"] = -(VOT * links.ff_time_min + nonfare)
links["ell"] = links.length_mi.clip(lower=0.15)


# Feeder buses are timed to train arrivals (NICE and Suffolk Transit both run
# LIRR-timed station routes), so the access wait is a 5 min timed transfer
# rather than half a 22 min headway, and 16 mph is a fairer feeder speed.
m = links.link_type == "ACCESS_TRANSIT"
links.loc[m, "ff_time_min"] = (links.length_mi / 16.0 * 60 + 8.0).round(2)[m]
links.loc[m, "phi_usd"] = -(VOT * links.loc[m, "ff_time_min"])
links["park_delay_min"] = 0.0

# egress: finite subway capacity for the priced links, none for the walk links
e = links.link_type == "EGRESS"
links.loc[e & (links.operator == "LOCAL"), "capacity_period"] = 25000.0
links.loc[e & (links.operator == "NONE"), "capacity_period"] = np.nan
links.loc[e & (links.operator == "LOCAL") & (links.cap_cost_per_unit == 0),
          "cap_cost_per_unit"] = 0.05

cols = ["link_id", "from_node", "to_node", "link_type", "operator", "mode",
        "branch", "length_mi", "ff_time_min", "ell", "phi_usd", "tau_usd",
        "fare_usd", "user_cost_usd", "capacity_period", "prov_cost_per_pax",
        "cap_cost_per_unit", "shared_capacity_key", "park_delay_min",
        "flow_true"]
links[cols].to_csv(f"{OUT}/links_p2.csv", index=False)
print(f"links_p2.csv: {len(links)} links, phi range "
      f"[{links.phi_usd.min():.2f}, {links.phi_usd.max():.2f}]")

# ============================================== 3. segments and segment flows
paths["od_seg"] = paths.tract + "|" + paths.zone
seg_defs = []
f_dest, f_odp = {}, {}
for r in paths.itertuples():
    if r.flow <= 0:
        continue
    ids = r.link_ids.split("|")
    for a in ids:
        f_dest[(r.zone, a)] = f_dest.get((r.zone, a), 0.0) + r.flow
        f_odp[(r.od_seg, a)] = f_odp.get((r.od_seg, a), 0.0) + r.flow

fd = pd.DataFrame([dict(segment=k[0], link_id=k[1], f_true=round(v, 6))
                   for k, v in f_dest.items()])
fo = pd.DataFrame([dict(segment=k[0], link_id=k[1], f_true=round(v, 6))
                   for k, v in f_odp.items()])
# f_seg_link.csv is the IO2 ground truth and is written by
# run_ground_truth_tau0.py from the administered-fare solve.  The MNL
# path-derived cells are kept separately so a rebuild of this stage cannot
# silently replace the ground truth -- it did once, and the sampling plans
# were drawn from 25,071 MNL cells instead of the 4,724 P2 cells.
fd.to_csv(f"{OUT}/f_seg_link_paths.csv", index=False)
fo.to_csv(f"{OUT}/f_seg_link_od.csv", index=False)
print(f"destination segments: 6, cells {len(fd)} | OD segments: "
      f"{fo.segment.nunique()}, cells {len(fo)}")

for z, g in od.groupby("d_node"):
    seg_defs.append(dict(segmentation="destination", segment=z,
                         sink_node=z, n_origins=g.o_node.nunique(),
                         demand=round(g.trips_am.sum(), 4)))
for (o, d), g in od.groupby(["o_node", "d_node"]):
    seg_defs.append(dict(segmentation="od_pair", segment=f"{o}|{d}",
                         sink_node=d, n_origins=1,
                         demand=round(g.trips_am.sum(), 6)))
pd.DataFrame(seg_defs).to_csv(f"{OUT}/segments.csv", index=False)

# node balance b_{i,n}: +production at each origin, -demand at the sink
bn = []
for z, g in od.groupby("d_node"):
    for r in g.itertuples():
        bn.append(dict(segmentation="destination", segment=z, node=r.o_node,
                       b=round(r.trips_am, 6)))
    bn.append(dict(segmentation="destination", segment=z, node=z,
                   b=round(-g.trips_am.sum(), 4)))
pd.DataFrame(bn).to_csv(f"{OUT}/b_node.csv", index=False)

print("\nnext: run_p2_ground_truth.py (P2 solve), then refresh_sampling.py")
